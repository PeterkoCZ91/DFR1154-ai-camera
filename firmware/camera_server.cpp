static esp_err_t roi_mask_post_handler(httpd_req_t *req) {
    if (check_basic_auth(req) != ESP_OK) return ESP_OK;
    set_cors_headers(req);

    char content[512];
    size_t recv_size = (req->content_len < sizeof(content) - 1) ? req->content_len : sizeof(content) - 1;
    int ret = httpd_req_recv(req, content, recv_size);
    if (ret <= 0) { httpd_resp_send_408(req); return ESP_FAIL; }
    content[ret] = '\0';

    StaticJsonDocument<512> doc;
    if (deserializeJson(doc, content)) {
        httpd_resp_set_type(req, "application/json");
        httpd_resp_set_status(req, "400 Bad Request");
        httpd_resp_send(req, "{\"error\":\"Invalid JSON\"}", HTTPD_RESP_USE_STRLEN);
        return ESP_FAIL;
    }

    // Accept: {"mask":"111011..."} or {"clear":true}
    if (doc.containsKey("clear")) {
        motionDetector.clearMask();
        httpd_resp_send(req, "{\"ok\":true,\"action\":\"cleared\"}", HTTPD_RESP_USE_STRLEN);
        return ESP_OK;
    }

    const char* mask = doc["mask"];
    if (mask) {
        int gw = motionDetector.getGridW();
        int gh = motionDetector.getGridH();
        int len = strlen(mask);
        int i = 0;
        for (int y = 0; y < gh && i < len; y++) {
            for (int x = 0; x < gw && i < len; x++, i++) {
                motionDetector.setBlockMask(x, y, mask[i] != '0');
            }
        }
        saveROIMask(mask, len);
        int masked = 0;
        for (int j = 0; j < len; j++) if (mask[j] == '0') masked++;
        Serial.printf("ROI mask set: %d blocks masked out of %d\n", masked, gw * gh);
        httpd_resp_set_type(req, "application/json");
        char resp[64];
        snprintf(resp, sizeof(resp), "{\"ok\":true,\"masked\":%d,\"total\":%d}", masked, gw * gh);
        httpd_resp_send(req, resp, HTTPD_RESP_USE_STRLEN);
        return ESP_OK;
    }

    httpd_resp_set_type(req, "application/json");
    httpd_resp_set_status(req, "400 Bad Request");
    httpd_resp_send(req, "{\"error\":\"need mask or clear\"}", HTTPD_RESP_USE_STRLEN);
    return ESP_FAIL;
}

// Motion Debug Endpoint -- returns full motion detection state + per-block motion grid
static esp_err_t motion_debug_handler(httpd_req_t *req) {
    set_cors_headers(req);
    httpd_resp_set_type(req, "application/json");

    int gw = motionDetector.getGridW();
    int gh = motionDetector.getGridH();

    // Build JSON response with motion state + block grid
    // Buffer: 2 grids of up to 64*48=3072 chars each + JSON overhead
    char* buf = (char*)malloc(8192);
    if (!buf) {
        httpd_resp_send_500(req);
        return ESP_FAIL;
    }

    int len = snprintf(buf, 8192,
        "{\"enabled\":%s,\"detected\":%s,\"pct\":%.1f,\"score\":%d,\"brightness\":%d,"
        "\"threshold\":%d,\"night\":%s,"
        "\"grid_w\":%d,\"grid_h\":%d,\"motion\":\"",
        config.motion_detection_enabled ? "true" : "false",
        motionDetector.isMotionDetected() ? "true" : "false",
        motionDetector.getMotionPercent(),
        motionDetector.getMotionScore(),
        motionDetector.getAvgBrightness(),
        motionDetector.getEffectivePixelThreshold(),
        motionDetector.getAvgBrightness() < MOTION_NIGHT_BRIGHTNESS ? "true" : "false",
        gw, gh
    );

    // Append block motion grid as "010010..." string
    for (int y = 0; y < gh && len < 8000; y++) {
        for (int x = 0; x < gw && len < 8000; x++) {
            buf[len++] = motionDetector.getBlockMotion(x, y) ? '1' : '0';
        }
    }

    // Append ROI mask
    len += snprintf(buf + len, 8192 - len, "\",\"mask\":\"");
    for (int y = 0; y < gh && len < 8000; y++) {
        for (int x = 0; x < gw && len < 8000; x++) {
            buf[len++] = motionDetector.getBlockMask(x, y) ? '1' : '0';
        }
    }
    len += snprintf(buf + len, 8192 - len, "\"}");

    httpd_resp_send(req, buf, len);
    free(buf);
    return ESP_OK;
}

