static esp_err_t zones_post_handler(httpd_req_t *req) {
    if (check_basic_auth(req) != ESP_OK) return ESP_OK;
    httpd_resp_set_type(req, "application/json");
    httpd_resp_set_hdr(req, "Access-Control-Allow-Origin", "*");

    char content[512];
    size_t recv_size = (req->content_len < sizeof(content) - 1) ? req->content_len : sizeof(content) - 1;
    int ret = httpd_req_recv(req, content, recv_size);
    if (ret <= 0) { httpd_resp_send_408(req); return ESP_FAIL; }
    content[ret] = '\0';

    StaticJsonDocument<512> doc;
    if (deserializeJson(doc, content)) {
        httpd_resp_set_status(req, "400 Bad Request");
        httpd_resp_sendstr(req, "{\"error\":\"Invalid JSON\"}");
        return ESP_FAIL;
    }

    // DELETE action via POST body: {"delete":"door"}
    if (doc.containsKey("delete")) {
        bool ok = deleteZone(doc["delete"] | "");
        httpd_resp_sendstr(req, ok ? "{\"ok\":true}" : "{\"error\":\"not found\"}");
        return ESP_OK;
    }

    Zone z = {};
    strlcpy(z.name,  doc["name"]  | "zone", ZONE_NAME_LEN);
    strlcpy(z.color, doc["color"] | "#ffffff", 8);
    z.alert = doc["alert"] | false;
    z.rect_count = 0;
    JsonArray rects = doc["rects"];
    if (rects) {
        for (JsonObject r : rects) {
            if (z.rect_count >= ZONE_MAX_RECTS) break;
            ZoneRect& zr = z.rects[z.rect_count++];
            zr.x = r["x"] | 0;
            zr.y = r["y"] | 0;
            zr.w = r["w"] | 1;
            zr.h = r["h"] | 1;
        }
    }
    if (z.rect_count == 0) {
        httpd_resp_set_status(req, "400 Bad Request");
        httpd_resp_sendstr(req, "{\"error\":\"need rects array\"}");
        return ESP_FAIL;
    }

    bool ok = addOrUpdateZone(z);
    httpd_resp_sendstr(req, ok ? "{\"ok\":true}" : "{\"error\":\"max zones reached\"}");
    return ESP_OK;
}

