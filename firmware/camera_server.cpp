// Handler: Rate-limited MJPEG stream (port 81, /detection-stream)
// Capped at ~30 FPS (33ms delay) to avoid overwhelming Python clients (A12_System).
// Full CORS headers for cross-origin fetch. Same ring buffer, separate client counter.
