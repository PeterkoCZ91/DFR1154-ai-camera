    doc["total_restarts"] = sys_stats.total_restarts;
    doc["last_restart_reason"] = sys_stats.last_restart_reason;
    
    // Overall health status
    bool healthy = true;
    String issues = "";
    
    if (ESP.getFreeHeap() < 50000) {
        healthy = false;
        issues += "low_memory,";
    }
    if (WiFi.RSSI() < -75) {
        healthy = false;
        issues += "weak_wifi,";
    }
    if (wifi_health.reconnect_count > 3) {
        healthy = false;
        issues += "unstable_wifi,";
    }
    
